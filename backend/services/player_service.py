# Sync helpers
# --------------------------------------------------------------------------
def sync_catalog(session: Session) -> int:
    """Insert/update every catalog entry (real players + fictional demo personas)."""
    changed = 0
    for entry in catalog.all_profiles():
        row = session.scalars(select(Player).where(Player.slug == entry["id"])).first()
        if row is None:
            row = Player(slug=entry["id"], folder=entry["folder"],
                         display_name=entry["name"])
            session.add(row)
        row.folder = entry["folder"]
        row.display_name = entry["name"]
        row.role = entry.get("role")
        row.batting_style = entry.get("batting_style")
        row.bowling_style = entry.get("bowling_style")
        row.jersey_number = entry.get("jersey_number")
        row.born = entry.get("born")
        row.bio = entry.get("bio")
        row.career_highlights = json.dumps(entry.get("career_highlights", []))
        row.fictional = bool(entry.get("fictional"))
        changed += 1
    session.flush()
    return changed


def _count_images(folder: Path) -> tuple[int, int]:
    if not folder.is_dir():
        return 0, 0
    valid = invalid = 0
    for path in folder.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in SUPPORTED_IMAGE_EXT:
            continue
        try:
            if path.stat().st_size > 0:
                valid += 1
            else:
                invalid += 1
        except OSError:
            invalid += 1
    return valid, invalid


def sync_dataset(session: Session) -> None:
    """Refresh dataset inventory rows for the real dataset and the demo dataset."""
    roots = [(settings.dataset_dir, "local")]
    if settings.demo_enabled:
        roots.append((settings.demo_dataset_dir, "demo"))

    for root, source in roots:
        players = {p.folder: p for p in session.scalars(select(Player)).all()}
        seen: set[str] = set()
        if not root.is_dir():
            continue
        for folder in sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith((".", "_"))):
            valid, invalid = _count_images(folder)
            seen.add(str(folder))
            player = players.get(folder.name)
            if player is None:
                # a dataset folder with no catalog entry: create a stub profile
                player = Player(slug=catalog.slugify(folder.name), folder=folder.name,
                                display_name=folder.name.replace("_", " "),
                                role="Not in the catalog",
                                bio=("This folder was found in the dataset but has no catalog "
                                     "entry. Add a profile in backend/catalog.py to show "
                                     "verified career facts here."))
                session.add(player)
                session.flush()
                players[folder.name] = player
            player.dataset_images = valid
            record = session.scalars(
                select(DatasetRecord).where(DatasetRecord.player_id == player.id,
                                            DatasetRecord.path == str(folder))
            ).first()
            if record is None:
                record = DatasetRecord(player_id=player.id, path=str(folder), source=source)
                session.add(record)
            record.source = source
            record.images_count = valid + invalid
            record.valid_images = valid
            record.invalid_images = invalid
            record.last_scanned_at = dt.datetime.now(dt.timezone.utc).replace(tzinfo=None)
            record.licence_note = (
                "Demo images were generated by an AI image model - no real person."
                if source == "demo" else
                "You are responsible for holding a valid licence for these images.")
        # remove stale records for folders that disappeared
        for record in session.scalars(select(DatasetRecord)).all():
            if record.source == source and record.path not in seen:
                session.delete(record)
    session.flush()


def sync_supported_flags(session: Session, model_classes: Optional[Iterable[str]] = None) -> None:
    """Mark players that the ACTIVE model can recognise."""
    classes = set(model_classes or [])
    for player in session.scalars(select(Player)).all():
        player.supported = player.folder in classes
    session.flush()


