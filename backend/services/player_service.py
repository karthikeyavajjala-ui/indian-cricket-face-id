def _avatar_url(player: Player, sample_urls: list[str]) -> str:
    if sample_urls:
        return sample_urls[0]
    return f"/api/players/{player.slug}/avatar.svg"


def media_root(source: str) -> Path:
    """Dataset root a '/media/...' URL maps to."""
    return settings.demo_dataset_dir if source == "demo" else settings.dataset_dir


def _sample_urls(session: Session, player: Player, limit: int = 3) -> list[str]:
    records = session.scalars(
        select(DatasetRecord).where(DatasetRecord.player_id == player.id)
    ).all()
    for record in records:
        folder = Path(record.path)
        if not folder.is_dir():
            continue
        files = sorted(p for p in folder.rglob("*")
                       if p.is_file() and p.suffix.lower() in SUPPORTED_IMAGE_EXT)
        if not files:
            continue
        root = media_root(record.source)
        urls = []
        for file in files[:limit]:
            try:
                rel = file.relative_to(root).as_posix()
            except ValueError:
                continue
            urls.append(f"/media/{record.source}/{rel}")
        if urls:
            return urls
    return []


def profile_payload(session: Session, player: Player, model_info: Optional[dict] = None,
                    dataset_configured: bool = True) -> dict:
    folder = player.folder
    samples = _sample_urls(session, player)
    entry = catalog.get_profile(player.slug) or {}
    highlights = []
    if player.career_highlights:
        try:
            highlights = json.loads(player.career_highlights)
        except json.JSONDecodeError:
            highlights = []
    model_block = model_info or {}
    groups = model_block.get("per_class", {})
    stats = groups.get(folder, {})
    counts = (model_block.get("class_samples") or {}).get(folder, {})
    dataset_source = "none"
    for record in session.scalars(select(DatasetRecord).where(DatasetRecord.player_id == player.id)):
        if record.valid_images:
            dataset_source = record.source
            break
    return {
        "id": player.slug,
        "folder": folder,
        "name": player.display_name,
        "role": player.role,
        "batting_style": player.batting_style,
        "bowling_style": player.bowling_style,
        "jersey_number": player.jersey_number,
        "born": player.born,
        "bio": player.bio,
        "career_highlights": highlights,
        "fictional": player.fictional,
        "supported": bool(player.supported),
        "dataset_images": player.dataset_images,
        "dataset_source": dataset_source,
        "avatar_url": _avatar_url(player, samples),
        "sample_images": samples,
        "model": {
            "trained": bool(player.supported),
            "dataset_images": counts.get("images", player.dataset_images),
            "augmented_variants": counts.get("augmented", 0),
            "training_vectors": counts.get("training_vectors", 0),
            "validation_support": stats.get("support"),
            "precision": stats.get("precision"),
            "recall": stats.get("recall"),
            "f1": stats.get("f1"),
            "note": ("Recognised by the active model" if player.supported else
                     ("In the catalog, but no training images yet - the model cannot "
                      "recognise this person." if dataset_configured else
                      "Dataset not configured.")),
        },
        "source_note": entry.get("source_note"),
    }


def list_players(session: Session, model_block: Optional[dict] = None,
                 dataset_configured: bool = True, include_unsupported: bool = True) -> list[dict]:
    rows = session.scalars(select(Player).order_by(Player.fictional, Player.display_name)).all()
    out = []
    for player in rows:
        has_images = (player.dataset_images or 0) > 0
        if not include_unsupported and not (player.supported or has_images):
            continue
        out.append(profile_payload(session, player, model_block, dataset_configured))
    # supported players first, then players with dataset images, then the rest
    out.sort(key=lambda p: (not p["supported"], p["dataset_images"] == 0, p["name"]))
    return out


def get_player(session: Session, player_id: str, model_block: Optional[dict] = None,
               dataset_configured: bool = True) -> Optional[dict]:
    player = session.scalars(
        select(Player).where((Player.slug == player_id) | (Player.folder == player_id))
    ).first()
    if player is None:
        entry = catalog.get_profile(player_id)
        if entry is None:
            return None
        # catalog entry exists but DB row is missing - make one
        sync_catalog(session)
        session.commit()
        player = session.scalars(select(Player).where(Player.slug == entry["id"])).first()
        if player is None:
            return None
    return profile_payload(session, player, model_block, dataset_configured)


def avatar_svg(name: str, seed_text: str = "") -> str:
    """Deterministic monogram avatar (used when a player has no dataset image)."""
    initials = "".join(part[0] for part in name.replace("(", " ").split()[:2]).upper() or "?"
    digest = sum(ord(ch) for ch in (seed_text or name))
    hue = digest % 360
    hue2 = (hue + 42) % 360
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200" width="200" height="200">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="hsl({hue},72%,46%)"/>
      <stop offset="100%" stop-color="hsl({hue2},78%,26%)"/>
    </linearGradient>
    <radialGradient id="s" cx="30%" cy="20%" r="80%">
      <stop offset="0%" stop-color="rgba(255,255,255,.35)"/>
      <stop offset="100%" stop-color="rgba(255,255,255,0)"/>
    </radialGradient>
  </defs>
  <rect width="200" height="200" rx="28" fill="url(#g)"/>
  <rect width="200" height="200" rx="28" fill="url(#s)"/>
  <circle cx="100" cy="176" r="74" fill="rgba(0,0,0,.18)"/>
  <text x="100" y="128" text-anchor="middle" font-family="Inter, Segoe UI, sans-serif"
        font-size="76" font-weight="700" fill="rgba(255,255,255,.95)">{initials}</text>
</svg>"""
